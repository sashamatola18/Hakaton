def device_for(metric, crew_index):
    """Пристрій конкретного астронавта для показника → {name, serial, place}."""
    name, code, place = DEVICES[metric]
    return {"name": name, "serial": f"{code}-{crew_index + 1:02d}", "place": place}


def cabin_device(key):
    name, serial, place = CABIN_DEVICES[key]
    return {"name": name, "serial": serial, "place": place}
